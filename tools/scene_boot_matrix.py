"""Render scene boot summaries (tools/scene_boot_check.py output) as a markdown table.

The table is generated, not transcribed: every row is a summary.json entry, so the
document cannot drift from the runs it describes. Later summaries override earlier
rows with the same scene id, which is how the SoulSilver scenes replace the rows a
HeartGold-only pass could not boot.

usage: scene_boot_matrix.py --summary WORK/summary.json [--summary WORK2/summary.json ...]
                            [--out docs/scene-boot-matrix.md]
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

KIND_ORDER = ["gym", "e4", "legendary", "event"]
KIND_TITLE = {"gym": "Gyms", "e4": "Elite Four / champion", "legendary": "Legendary and Red",
              "event": "Story milestones"}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--summary", action="append", required=True)
    ap.add_argument("--scenes", default=str(Path(__file__).resolve().parent.parent /
                                            "registry" / "hgss-us.scenes.json"),
                    help="Current scene registry; ids not in it are dropped (a run can be older than the registry).")
    ap.add_argument("--out", default="")
    opts = ap.parse_args()

    current = {s["id"]: s["game"] for s in
               json.load(open(opts.scenes, encoding="utf-8"))["scenes"]}
    merged: dict[str, dict] = {}
    runs = []
    dropped: set[str] = set()
    for path in opts.summary:
        summary = json.load(open(path, encoding="utf-8"))
        roms = sorted({e.get("rom", "") for e in summary["results"] if e.get("rom")})
        runs.append({"path": path, "base": summary.get("base", ""), "rom": summary.get("rom", ""),
                     "roms": roms, "passed": summary.get("passed"), "count": summary.get("count")})
        for entry in summary["results"]:
            if entry["id"] not in current:
                dropped.add(entry["id"])
                continue
            entry["game"] = entry.get("game") or current[entry["id"]]
            merged[entry["id"]] = entry

    results = sorted(merged.values(), key=lambda r: (KIND_ORDER.index(r["kind"]),
                                                     r["id"]))
    lines = [
        "# Scene boot matrix",
        "",
        "Generated by `tools/scene_boot_matrix.py` from `tools/scene_boot_check.py` runs.",
        "Each row composes the scene onto its base preset with `hgss-save story scene apply`,",
        "boots the result headless, and requires the live player location to be the scene tile",
        "(the post-load tile where the map's own script moves the player).",
        "",
    ]
    for run in runs:
        roms = ", ".join(f"`{r}`" for r in (run["roms"] or [run["rom"]]))
        lines.append(f"- run `{run['path']}`: {run['passed']}/{run['count']} reached their tile, "
                     f"rom(s) {roms}")
    lines += ["", f"Total rows: {len(results)}", ""]
    missing = sorted(current - merged.keys())
    if missing:
        lines += [f"Not run in these summaries: {', '.join('`' + m + '`' for m in missing)}", ""]
    if dropped:
        lines += [f"Dropped (no longer in the registry): {', '.join('`' + d + '`' for d in sorted(dropped))}", ""]

    for kind in KIND_ORDER:
        rows = [r for r in results if r.get("kind") == kind]
        if not rows:
            continue
        lines += [f"## {KIND_TITLE[kind]}", "",
                  "| scene | game | base | map | save tile | asserted tile | result |",
                  "|---|---|---|---|---|---|---|"]
        for r in rows:
            after = r.get("spawn_after") or {}
            asserted = f"({after.get('x')},{after.get('y')})" if after else f"({r['x']},{r['y']})"
            ok = "ok" if r.get("boot_ok") else f"FAIL ({r.get('error', '')[:60]})"
            lines.append(f"| `{r['id']}` | {r.get('game', '')} | `{r['base_preset']}` | "
                         f"{r['map']} | ({r['x']},{r['y']}) | {asserted} | {ok} |")
        lines.append("")

    text = "\n".join(lines) + "\n"
    if opts.out:
        Path(opts.out).write_text(text, encoding="utf-8")
        print(f"{len(results)} rows -> {opts.out}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
